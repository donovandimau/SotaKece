'use strict';
// Isolated synthetic Postgres fixture for Talanoa voice notes; never connects to Supabase or a live DB.
// POSIX: NODE_PATH="$PWD/tests/talanoa-tools/node_modules" node tests/run-talanoa-voice-db.cjs
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {PGlite}=require(process.env.PGLITE_MODULE||'@electric-sql/pglite');
const root=path.resolve(__dirname,'..');
const sql=f=>fs.readFileSync(path.join(root,'supabase/migrations',f),'utf8');
const ANA='11111111-1111-1111-1111-111111111111',BO='22222222-2222-2222-2222-222222222222';
const clip=(owner,n)=>`${owner}/aaaaaaaa-aaaa-4aaa-8aaa-${String(n).padStart(12,'0')}.webm`;
const fixture=String.raw`
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN;
CREATE SCHEMA auth;
CREATE SCHEMA bulavata;
GRANT USAGE ON SCHEMA auth, bulavata, public TO anon,authenticated;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
 SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid;
$$;
GRANT EXECUTE ON FUNCTION auth.uid() TO anon,authenticated;
CREATE TABLE bulavata.profiles (
 id uuid PRIMARY KEY, handle text UNIQUE NOT NULL, display_name text NOT NULL DEFAULT '',
 avatar_emoji text DEFAULT '🌺', room_accent text NOT NULL DEFAULT '#4FA8D8', created_at timestamptz DEFAULT now()
);
ALTER TABLE bulavata.profiles ENABLE ROW LEVEL SECURITY;
CREATE TABLE bulavata.friendships (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 requester uuid NOT NULL REFERENCES bulavata.profiles(id) ON DELETE CASCADE,
 addressee uuid NOT NULL REFERENCES bulavata.profiles(id) ON DELETE CASCADE,
 status text NOT NULL DEFAULT 'pending',created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(requester,addressee),CHECK(requester<>addressee)
);
INSERT INTO bulavata.profiles(id,handle,display_name) VALUES ('${ANA}','ana','Ana'),('${BO}','bo','Bo');
`;
const storage=String.raw`
CREATE SCHEMA storage;
GRANT USAGE ON SCHEMA storage TO anon,authenticated;
CREATE TABLE storage.buckets (id text PRIMARY KEY, name text, public boolean, file_size_limit bigint, allowed_mime_types text[]);
CREATE TABLE storage.objects (id uuid DEFAULT gen_random_uuid() PRIMARY KEY, bucket_id text, name text, owner uuid, owner_id text);
ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
CREATE FUNCTION storage.foldername(name text) RETURNS text[] LANGUAGE sql IMMUTABLE AS $$ SELECT (string_to_array(name,'/'))[1:array_length(string_to_array(name,'/'),1)-1]; $$;
`;
(async()=>{
 const db=new PGlite();let passed=0;
 const ok=(cond,name)=>{assert.ok(cond,name);passed++;process.stdout.write('PASS '+name+'\n');};
 const as=async(role,sub)=>{await db.exec(`RESET ROLE; SELECT set_config('request.jwt.claim.sub','${sub||''}',false); SET ROLE ${role};`);};
 const admin=async()=>{await db.exec(`RESET ROLE;`);};
 const fails=async(q,params,word)=>{try{await db.query(q,params);}catch(e){return String(e.message).includes(word)?true:(()=>{throw e;})();}return false;};
 const upload=async(name,owner,useOwnerId)=>{await admin();await db.query(`INSERT INTO storage.objects(bucket_id,name,owner,owner_id) VALUES ('talanoa-voice',$1,$2,$3)`,[name,useOwnerId?null:owner,useOwnerId?owner:null]);};
 const POST=`SELECT public.bv_talanoa_post_voice($1,$2,$3,$4) AS p`;
 try {
  await db.exec(fixture);
  await db.exec(sql('20261030100000_sota_free_gifts.sql'));
  await db.exec(sql('20261109000000_sota_talanoa_wall.sql'));
  await db.exec(sql('20261109200000_sota_sere.sql'));
  await db.exec(sql('20261109210000_sota_sere_service_grants.sql'));
  await db.exec(sql('20261109220000_sota_sere_engines.sql'));
  await db.exec(storage);
  // an existing text post made before the change
  await as('authenticated',ANA);
  const old=(await db.query(`SELECT public.bv_talanoa_post('Bula from before') AS p`)).rows[0].p;
  await admin();
  await db.exec(sql('20261110150000_sota_talanoa_voice.sql'));
  await db.exec(sql('20261110150000_sota_talanoa_voice.sql'));
  ok(true,'the migration runs, and runs a second time without error');

  const bucket=(await db.query(`SELECT * FROM storage.buckets WHERE id='talanoa-voice'`)).rows[0];
  ok(bucket&&bucket.public===true&&Number(bucket.file_size_limit)===1572864&&bucket.allowed_mime_types.join()==='audio/webm,audio/mp4,audio/ogg','the bucket is public, capped at 1.5 MB and audio only');
  const policies=(await db.query(`SELECT policyname,cmd,roles::text AS roles FROM pg_policies WHERE schemaname='storage' AND policyname LIKE 'talanoa_voice_%' ORDER BY policyname`)).rows;
  ok(policies.length===3&&policies.map(p=>p.cmd).join()==='DELETE,INSERT,SELECT','three storage rules: own-folder insert, own-folder delete, read');

  await as('authenticated',ANA);
  const feed0=(await db.query(`SELECT public.bv_talanoa_feed() AS f`)).rows[0].f;
  ok(feed0.length===1&&feed0[0].id===old.id&&feed0[0].voice===null&&feed0[0].body==='Bula from before','existing posts are untouched and carry no voice note');

  ok(await fails(POST,[clip(ANA,1),12,null,null],'VOICE_BAD'),'a recording that was never uploaded is refused');
  await upload(clip(ANA,1),ANA);await upload(clip(ANA,2),ANA,true);await upload(clip(BO,1),BO);
  await as('authenticated',ANA);
  ok(await fails(POST,[clip(BO,1),12,null,null],'VOICE_BAD'),'another member\'s recording is refused');
  ok(await fails(POST,[clip(ANA,1),0,null,null],'VOICE_BAD')&&await fails(POST,[clip(ANA,1),61,null,null],'VOICE_BAD'),'length must be 1 to 60 seconds');
  ok(await fails(POST,['../'+clip(ANA,1),10,null,null],'VOICE_BAD')&&await fails(POST,[ANA+'/x.exe',10,null,null],'VOICE_BAD')&&await fails(POST,['',0,null,null],'VOICE_BAD'),'only a plain <member>/<id>.webm|m4a|ogg path is accepted; the empty probe is refused cleanly');
  ok(await fails(POST,[clip(ANA,1),10,'x'.repeat(281),null],'TOO_LONG'),'words with a voice note keep the 280 limit');

  const v1=(await db.query(POST,[clip(ANA,1),12,null,null])).rows[0].p;
  ok(v1.voice.path===clip(ANA,1)&&v1.voice.seconds===12&&v1.body==='🎙️ Voice note'&&v1.mine===true&&v1.reply_to===null,'a voice note posts with a default caption and comes back in feed shape');
  ok(await fails(POST,[clip(ANA,1),12,null,null],'VOICE_BAD'),'one recording cannot be attached twice');
  const v2=(await db.query(POST,[clip(ANA,2),5,'Sota tale!',v1.id])).rows[0].p;
  ok(v2.reply_to===v1.id&&v2.body==='Sota tale!'&&v2.voice.seconds===5,'a voice reply works, with its own words, for a file recorded under owner_id');
  await upload(clip(ANA,3),ANA);await as('authenticated',ANA);
  const v3=(await db.query(POST,[clip(ANA,3),7,null,v2.id])).rows[0].p;
  ok(v3.reply_to===v1.id,'a voice reply to a reply joins the same thread');
  ok(await fails(POST,[clip(ANA,3).replace('000003','000009'),7,null,999999],'VOICE_BAD'),'checks run before the thread lookup');

  await as('authenticated',BO);
  const seen=(await db.query(`SELECT public.bv_talanoa_feed() AS f`)).rows[0].f;
  ok(seen.find(p=>p.id===v1.id).voice.path===clip(ANA,1)&&seen.find(p=>p.id===v1.id).mine===false&&seen.find(p=>p.id===v1.id).reply_count===2,'another member sees the voice note and its reply count on the wall');
  const thread=(await db.query(`SELECT public.bv_talanoa_feed('latest',now(),20,0,null,null,null,null,$1) AS f`,[v1.id])).rows[0].f;
  ok(thread.length===2&&thread.every(p=>p.voice&&p.voice.path.startsWith(ANA+'/')),'voice replies come back in the thread');

  await as('anon','');
  ok(await fails(POST,[clip(ANA,1),12,null,null],'permission denied'),'a signed-out visitor cannot call it');

  await admin();
  ok(await fails(`INSERT INTO bulavata.talanoa_posts(author,body,voice_path,voice_seconds) VALUES ($1,'x',$2,5)`,[BO,clip(ANA,7)],'talanoa_posts_voice_ok'),'the table itself refuses a voice file from someone else\'s folder');
  ok(await fails(`INSERT INTO bulavata.talanoa_posts(author,body,voice_path) VALUES ($1,'x',$2)`,[ANA,clip(ANA,7)],'talanoa_posts_voice_ok'),'path and length must be set together');

  for(let i=0;i<27;i++){await db.query(`INSERT INTO bulavata.talanoa_posts(author,body,voice_path,voice_seconds) VALUES ($1,'v',$2,3)`,[ANA,clip(ANA,100+i)]);}
  await upload(clip(ANA,50),ANA);await as('authenticated',ANA);
  ok(await fails(POST,[clip(ANA,50),3,null,null],'VOICE_LIMIT'),'thirty voice notes in a day is the limit');
  await as('authenticated',ANA);
  await db.query(`SELECT public.bv_talanoa_delete($1)`,[v1.id]);
  const after=(await db.query(`SELECT count(*)::int AS n FROM bulavata.talanoa_posts WHERE id IN ($1,$2,$3)`,[v1.id,v2.id,v3.id])).rows[0].n;
  ok(after===0,'removing a voice post removes it and its replies');
  process.stdout.write(`Talanoa voice isolated Postgres: ${passed} checks passed.\n`);
 } finally {await db.close();}
})().catch(error=>{process.stderr.write((error.stack||String(error))+'\n');process.exitCode=1;});
