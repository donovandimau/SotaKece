with
rels as (select c.oid, c.relkind, c.relrowsecurity, c.relforcerowsecurity, c.relacl, c.reloptions, n.nspname, c.relname, format('%I.%I', n.nspname, c.relname) fq from pg_class c join pg_namespace n on n.oid=c.relnamespace where (n.nspname='bulavata' or (n.nspname='public' and c.relname like 'bv\_%')) and c.relkind in ('r','v','S')),
fns as (select p.oid, p.proacl, format('%I.%I(%s)', n.nspname, p.proname, pg_get_function_identity_arguments(p.oid)) sig from pg_proc p join pg_namespace n on n.oid=p.pronamespace where (n.nspname in ('bulavata','bulavata_talanoa_private') or (n.nspname='public' and (p.proname like 'bv\_%' or p.proname like 'sota\_%'))) and p.prokind in ('f','p')),
roles as (select oid, rolname from pg_roles where rolname in ('anon','authenticated','service_role') union all select 0, 'public'),
ddl(sec, ord, line) as (
  select 0, 0, '-- Sota Kece database schema, exported from live dimau-core-sydney (aqfzpaczyodhugsgqvxi) on ' || to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI') || ' UTC.' || E'\n' ||
    '-- Generated from the system catalogue by a read-only query (see supabase/baseline/README.md). Do not hand-edit: re-export instead.' || E'\n' ||
    '-- Covers schemas bulavata and bulavata_talanoa_private plus the public bv_*/sota_* functions, views and tables. Storage, realtime and cron are in sota_kece_platform.sql.' || E'\n' ||
    '-- Needs: roles anon, authenticated, service_role; auth.uid(); auth.users(id); extensions.digest / extensions.gen_random_bytes (pgcrypto); storage.objects.' || E'\n\n' ||
    'set check_function_bodies = off;' || E'\n' ||
    '-- Column defaults call pgcrypto without a schema (as Supabase allows), so extensions must be on the path.' || E'\n' ||
    'set search_path = public, extensions;' || E'\n' || 'create schema if not exists bulavata;' || E'\n' || 'create schema if not exists bulavata_talanoa_private;'
  union all
  select 1, r.oid::bigint, format('create sequence if not exists %s as %s start %s increment %s minvalue %s maxvalue %s cache %s%s;', r.fq, format_type(s.seqtypid, null), s.seqstart, s.seqincrement, s.seqmin, s.seqmax, s.seqcache, case when s.seqcycle then ' cycle' else '' end)
  from rels r join pg_sequence s on s.seqrelid=r.oid
  where not exists (select 1 from pg_depend d where d.objid=r.oid and d.classid='pg_class'::regclass and d.deptype='i')
  union all
  select 2, r.oid::bigint, 'create table if not exists ' || r.fq || ' (' || E'\n  ' ||
    (select string_agg(format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod)) ||
        case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end ||
        case when a.attgenerated='s' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
             when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end ||
        case when a.attnotnull then ' not null' else '' end, E',\n  ' order by a.attnum)
     from pg_attribute a left join pg_attrdef ad on ad.adrelid=a.attrelid and ad.adnum=a.attnum
     where a.attrelid=r.oid and a.attnum>0 and not a.attisdropped) || E'\n);'
  from rels r where r.relkind='r'
  union all
  select 3, r.oid::bigint, format('alter sequence %s owned by %s.%I;', r.fq, t.fq, a.attname)
  from rels r join pg_depend d on d.objid=r.oid and d.classid='pg_class'::regclass and d.deptype='a' and d.refclassid='pg_class'::regclass
  join rels t on t.oid=d.refobjid join pg_attribute a on a.attrelid=d.refobjid and a.attnum=d.refobjsubid
  union all
  select 4, (case con.contype when 'p' then 0 when 'u' then 1 when 'x' then 2 when 'c' then 3 else 9 end)::bigint * 100000000 + con.oid::bigint,
    format('alter table only %s add constraint %I %s;', r.fq, con.conname, pg_get_constraintdef(con.oid))
  from pg_constraint con join rels r on r.oid=con.conrelid where con.contype in ('p','u','x','c','f')
  union all
  select 5, i.indexrelid::bigint, pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i join rels r on r.oid=i.indrelid
  where not exists (select 1 from pg_constraint con where con.conindid=i.indexrelid and con.conrelid=i.indrelid)
  union all
  select 6, f.oid::bigint, pg_get_functiondef(f.oid) || ';' from fns f
  union all
  select 7, r.oid::bigint, 'create or replace view ' || r.fq || coalesce(' with (' || array_to_string(r.reloptions, ', ') || ')', '') || ' as' || E'\n' || pg_get_viewdef(r.oid, true)
  from rels r where r.relkind='v'
  union all
  select 8, t.oid::bigint, pg_get_triggerdef(t.oid) || ';'
  from pg_trigger t join rels r on r.oid=t.tgrelid where not t.tgisinternal
  union all
  select 9, r.oid::bigint, 'alter table ' || r.fq || ' enable row level security;' || case when r.relforcerowsecurity then E'\nalter table ' || r.fq || ' force row level security;' else '' end
  from rels r where r.relkind='r' and r.relrowsecurity
  union all
  select 10, p.oid::bigint, format('create policy %I on %s as %s for %s to %s%s%s;', p.polname, r.fq,
      case when p.polpermissive then 'permissive' else 'restrictive' end,
      case p.polcmd when 'r' then 'select' when 'a' then 'insert' when 'w' then 'update' when 'd' then 'delete' else 'all' end,
      (select string_agg(case when x=0 then 'public' else quote_ident(pg_get_userbyid(x)) end, ', ') from unnest(p.polroles) x),
      coalesce(' using (' || pg_get_expr(p.polqual, p.polrelid) || ')', ''),
      coalesce(' with check (' || pg_get_expr(p.polwithcheck, p.polrelid) || ')', ''))
  from pg_policy p join rels r on r.oid=p.polrelid
  union all
  select 11, 0, (select coalesce(string_agg(format('grant %s on schema %I to %s;', lower(g.privilege_type), n.nspname, ro.rolname), E'\n' order by n.nspname, ro.rolname, g.privilege_type), '')
     from pg_namespace n, aclexplode(n.nspacl) g join roles ro on ro.oid=g.grantee where n.nspname in ('bulavata','bulavata_talanoa_private'))
  union all
  select 12, r.oid::bigint, format('revoke all on %s %s from public, anon, authenticated, service_role;', case when r.relkind='S' then 'sequence' else 'table' end, r.fq) ||
    coalesce(E'\n' || (select string_agg(format('grant %s on %s %s to %s;', string_agg_priv, case when r.relkind='S' then 'sequence' else 'table' end, r.fq, rolname), E'\n' order by rolname)
       from (select ro.rolname, string_agg(lower(g.privilege_type), ', ' order by g.privilege_type) string_agg_priv from aclexplode(r.relacl) g join roles ro on ro.oid=g.grantee group by ro.rolname) z), '')
  from rels r
  union all
  select 13, f.oid::bigint, format('revoke all on function %s from public, anon, authenticated, service_role;', f.sig) ||
    coalesce(E'\n' || (select string_agg(format('grant execute on function %s to %s;', f.sig, ro.rolname), E'\n' order by ro.rolname)
       from aclexplode(coalesce(f.proacl, acldefault('f', (select proowner from pg_proc where oid=f.oid)))) g join roles ro on ro.oid=g.grantee where g.privilege_type='EXECUTE'), '')
  from fns f
)
select string_agg(line, E'\n\n' order by sec, ord) || E'\n' as content from ddl where line <> ''