-- Sota Kece — report, block, and "you made someone's Top Mates" (12 Nov 2026).
-- 1. Report: any member can report a wall post or a room. Reports are private: nobody can read
--    them through the app, only the owner from the database. 20 reports a day per member.
-- 2. Block: a member can block another. Blocking takes each out of the other's Top Mates, and the
--    app hides the blocked person's wall posts. Only the blocker can see their own block list.
-- 3. Top Mates: when someone puts you in their Top Mates you hear about it in Activity.
-- Safe to run twice. Builds on sota_activity (notifications) and sota_talanoa_wall.

create table if not exists bulavata.blocks (
  blocker    uuid not null references bulavata.profiles(id) on delete cascade,
  blocked    uuid not null references bulavata.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker, blocked),
  check (blocker <> blocked)
);
create index if not exists blocks_blocked_idx on bulavata.blocks (blocked);

create table if not exists bulavata.reports (
  id          bigint generated by default as identity primary key,
  reporter    uuid not null references bulavata.profiles(id) on delete cascade,
  target_kind text not null check (target_kind in ('post','profile')),
  target_id   text not null check (char_length(target_id) between 1 and 64),
  reason      text not null check (reason in ('spam','bullying','hate','sexual','violence','underage','scam','other')),
  note        text check (note is null or char_length(note) <= 500),
  status      text not null default 'open' check (status in ('open','actioned','dismissed')),
  created_at  timestamptz not null default now(),
  unique (reporter, target_kind, target_id)
);
create index if not exists reports_open_idx on bulavata.reports (status, created_at desc);

alter table bulavata.blocks  enable row level security;
alter table bulavata.reports enable row level security;
drop policy if exists blocks_own on bulavata.blocks;
create policy blocks_own on bulavata.blocks for select to authenticated using (blocker = (select auth.uid()));
grant select on bulavata.blocks to authenticated;
-- reports: no policy at all, so no member can read or write them directly.

-- ---------------------------------------------------------------- block / unblock / list
create or replace function public.bv_block(p_member uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare me uuid := (select auth.uid());
begin
  if me is null then raise exception 'NOT_SIGNED_IN'; end if;
  if p_member is null or p_member = me then raise exception 'BAD_MEMBER'; end if;
  if not exists (select 1 from bulavata.profiles where id = p_member) then raise exception 'GONE'; end if;
  insert into bulavata.blocks (blocker, blocked) values (me, p_member) on conflict do nothing;
  delete from bulavata.top_friends where (owner = me and friend = p_member) or (owner = p_member and friend = me);
end $$;

create or replace function public.bv_unblock(p_member uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare me uuid := (select auth.uid());
begin
  if me is null then raise exception 'NOT_SIGNED_IN'; end if;
  delete from bulavata.blocks where blocker = me and blocked = p_member;
end $$;

create or replace function public.bv_blocked()
returns jsonb language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_agg(jsonb_build_object('id', b.blocked, 'handle', p.handle, 'display_name', p.display_name) order by b.created_at desc), '[]'::jsonb)
  from bulavata.blocks b join bulavata.profiles p on p.id = b.blocked
  where b.blocker = (select auth.uid());
$$;

-- ---------------------------------------------------------------- report
create or replace function public.bv_report(p_kind text, p_id text, p_reason text, p_note text default null)
returns void language plpgsql security definer set search_path = '' as $$
declare me uuid := (select auth.uid()); n text := nullif(btrim(coalesce(p_note, '')), '');
begin
  if me is null then raise exception 'NOT_SIGNED_IN'; end if;
  if p_kind not in ('post','profile') or p_id is null or char_length(p_id) not between 1 and 64 then raise exception 'BAD_TARGET'; end if;
  if p_reason not in ('spam','bullying','hate','sexual','violence','underage','scam','other') then raise exception 'BAD_REASON'; end if;
  if n is not null and char_length(n) > 500 then raise exception 'TOO_LONG'; end if;
  if (select count(*) from bulavata.reports where reporter = me and created_at > now() - interval '24 hours') >= 20 then
    raise exception 'REPORT_LIMIT';
  end if;
  insert into bulavata.reports (reporter, target_kind, target_id, reason, note) values (me, p_kind, p_id, p_reason, n)
  on conflict (reporter, target_kind, target_id) do update set reason = excluded.reason, note = excluded.note, created_at = now(), status = 'open';
end $$;

revoke execute on function public.bv_block(uuid), public.bv_unblock(uuid), public.bv_blocked(), public.bv_report(text, text, text, text) from public, anon;
grant  execute on function public.bv_block(uuid), public.bv_unblock(uuid), public.bv_blocked(), public.bv_report(text, text, text, text) to authenticated;

-- ---------------------------------------------------------------- Top Mates in Activity
do $$
declare c text;
begin
  select conname into c from pg_constraint
   where conrelid = 'bulavata.notifications'::regclass and contype = 'c'
     and pg_get_constraintdef(oid) like '%kind%' and pg_get_constraintdef(oid) like '%reaction%';
  if c is not null then execute format('alter table bulavata.notifications drop constraint %I', c); end if;
  alter table bulavata.notifications add constraint notifications_kind_check
    check (kind in ('reaction','reply','mention','friend_request','friend_accepted','wall','rsvp','joined','tip','top_mate'));
end $$;

create or replace function bulavata.top_mate_added()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.friend is not null and new.friend <> new.owner
     and not exists (select 1 from bulavata.blocks b where (b.blocker = new.friend and b.blocked = new.owner)) then
    perform bulavata.notify(new.friend, new.owner, 'top_mate', 'profile', 0, '#' || new.slot);
  end if;
  return new;
end $$;
drop trigger if exists top_mate_added on bulavata.top_friends;
create trigger top_mate_added after insert on bulavata.top_friends for each row execute function bulavata.top_mate_added();
