-- Sota Kece — the share engine.
-- Any wall post can leave the app as a link that works for anyone, and every link remembers who
-- sent it: opens are counted, and a new member who joins through it is credited to the sharer,
-- who hears about it in Activity. Builds on the Talanoa Wall (20261109000000). No table is readable
-- by anon; the public page reads one card through bv_talanoa_shared, where the token is the key.

create table bulavata.talanoa_shares (
  token      text primary key check (token ~ '^[a-f0-9]{32}$'),
  post_id    bigint not null references bulavata.talanoa_posts(id) on delete cascade,
  sharer     uuid   not null references bulavata.profiles(id) on delete cascade,
  opens      integer not null default 0,
  joins      integer not null default 0,
  created_at timestamptz not null default now(),
  unique (post_id, sharer)
);
create index talanoa_shares_sharer_idx on bulavata.talanoa_shares (sharer, created_at desc);

create table bulavata.referrals (
  id         bigint generated by default as identity primary key,
  member     uuid not null unique references bulavata.profiles(id) on delete cascade,
  sharer     uuid not null references bulavata.profiles(id) on delete cascade,
  token      text references bulavata.talanoa_shares(token) on delete set null,
  created_at timestamptz not null default now(),
  check (member <> sharer)
);
create index referrals_sharer_idx on bulavata.referrals (sharer, created_at desc);

alter table bulavata.talanoa_shares enable row level security;
alter table bulavata.referrals      enable row level security;
-- A member sees their own links and the people who joined through them; nothing else, nobody else.
create policy shares_own    on bulavata.talanoa_shares for select to authenticated using (sharer = (select auth.uid()));
create policy referrals_own on bulavata.referrals      for select to authenticated using (sharer = (select auth.uid()));
grant select on bulavata.talanoa_shares, bulavata.referrals to authenticated;

-- Activity learns one more kind: somebody joined through your link.
do $$
declare c text;
begin
  select conname into c from pg_constraint
   where conrelid = 'bulavata.notifications'::regclass and contype = 'c'
     and pg_get_constraintdef(oid) like '%kind%' and pg_get_constraintdef(oid) like '%reaction%';
  if c is not null then execute format('alter table bulavata.notifications drop constraint %I', c); end if;
  alter table bulavata.notifications add constraint notifications_kind_check
    check (kind in ('reaction','reply','mention','friend_request','friend_accepted','wall','rsvp','joined'));
end $$;

-- ---------------------------------------------------------------- mint a link (member)
-- One token per member per post, so sharing the same post twice gives the same link.
create or replace function public.bv_talanoa_share(p_id bigint)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  me uuid := (select auth.uid());
  t text;
  p record;
begin
  if me is null then raise exception 'NOT_SIGNED_IN'; end if;
  select x.id, x.body, pr.handle, pr.display_name into p
    from bulavata.talanoa_posts x join bulavata.profiles pr on pr.id = x.author where x.id = p_id;
  if not found then raise exception 'GONE'; end if;
  select s.token into t from bulavata.talanoa_shares s where s.post_id = p_id and s.sharer = me;
  if t is null then
    t := md5(gen_random_uuid()::text || clock_timestamp()::text || me::text);
    insert into bulavata.talanoa_shares (token, post_id, sharer) values (t, p_id, me)
      on conflict (post_id, sharer) do nothing;
    select s.token into t from bulavata.talanoa_shares s where s.post_id = p_id and s.sharer = me;
  end if;
  return jsonb_build_object('token', t, 'path', '/p/' || p_id::text || '/' || t,
    'id', p.id, 'body', p.body, 'handle', p.handle, 'display_name', p.display_name);
end $$;

-- ---------------------------------------------------------------- read a shared card (anyone)
-- Only a post that a member chose to share is readable here, and only with that member's token.
-- Counts the open. Returns null for anything that does not match, so ids cannot be probed.
create or replace function public.bv_talanoa_shared(p_post bigint, p_token text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  s bulavata.talanoa_shares%rowtype;
  card jsonb;
begin
  if p_token is null or p_token !~ '^[a-f0-9]{32}$' then return null; end if;
  select * into s from bulavata.talanoa_shares where token = p_token and post_id = p_post;
  if not found then return null; end if;
  update bulavata.talanoa_shares set opens = opens + 1 where token = s.token;
  select jsonb_build_object(
      'id', x.id, 'body', x.body, 'created_at', x.created_at,
      'like_count', x.like_count, 'reply_count', x.reply_count,
      'handle', pr.handle, 'display_name', pr.display_name, 'avatar_emoji', pr.avatar_emoji, 'accent', pr.room_accent,
      'sharer', jsonb_build_object('handle', sp.handle, 'display_name', sp.display_name),
      'quote', (select jsonb_build_object('body', q.body, 'handle', qp.handle, 'display_name', qp.display_name)
                from bulavata.talanoa_posts q join bulavata.profiles qp on qp.id = q.author where q.id = x.quote_of))
    into card
    from bulavata.talanoa_posts x
    join bulavata.profiles pr on pr.id = x.author
    join bulavata.profiles sp on sp.id = s.sharer
   where x.id = s.post_id;
  return card;
end $$;

-- ---------------------------------------------------------------- credit a sign-up (new member)
-- Called once by the app right after a room is created. A member is credited at most once, never
-- to themselves, and only while their account is less than a day old: an old account following a
-- link is a visit, not a sign-up.
create or replace function public.bv_referral_claim(p_token text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  me uuid := (select auth.uid());
  s bulavata.talanoa_shares%rowtype;
  h text;
  done boolean := false;
begin
  if me is null then raise exception 'NOT_SIGNED_IN'; end if;
  if p_token is null or p_token !~ '^[a-f0-9]{32}$' then return jsonb_build_object('claimed', false); end if;
  select * into s from bulavata.talanoa_shares where token = p_token;
  if not found or s.sharer = me then return jsonb_build_object('claimed', false); end if;
  if (select created_at from bulavata.profiles where id = me) < now() - interval '1 day' then
    return jsonb_build_object('claimed', false);
  end if;
  insert into bulavata.referrals (member, sharer, token) values (me, s.sharer, s.token)
    on conflict (member) do nothing;
  done := found;
  if done then
    update bulavata.talanoa_shares set joins = joins + 1 where token = s.token;
    select handle into h from bulavata.profiles where id = me;
    perform bulavata.notify(s.sharer, me, 'joined', 'profile', 0, coalesce(h, ''));
  end if;
  return jsonb_build_object('claimed', done, 'sharer', (select handle from bulavata.profiles where id = s.sharer));
end $$;

revoke execute on function
  public.bv_talanoa_share(bigint), public.bv_talanoa_shared(bigint, text), public.bv_referral_claim(text)
  from public, anon;
grant execute on function public.bv_talanoa_share(bigint), public.bv_referral_claim(text) to authenticated;
grant execute on function public.bv_talanoa_shared(bigint, text) to anon, authenticated;
