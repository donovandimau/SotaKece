-- Sota Kece — coins, tipping and payouts.
-- Coins are a closed loop on top of the FJD wallet that already exists here: members buy coin packs
-- from their wallet, tip coins on Talanoa Wall posts (Sota Kece keeps a fee), and makers move the
-- coins they earned back into their wallet. One ledger for money (bulavata.transactions), one for
-- coins (bulavata.coin_ledger), both append-only, both reconcilable.
-- Buying and paying out are OFF (coin_settings.buy_on / payout_on = false): the wallet is held until
-- the Reserve Bank of Fiji approves it, and coins can only come from the wallet, so nothing moves
-- until the owner flips those two switches. Everything is built, tested and switchable.

-- ---------------------------------------------------------------- settings and packs
create table bulavata.coin_settings (
  id               boolean primary key default true check (id),
  coin_sene        integer not null default 10   check (coin_sene between 1 and 1000),  -- 1 coin = FJ$0.10
  fee_bps          integer not null default 3000 check (fee_bps between 0 and 9000),    -- Sota Kece keeps 30% of a tip
  tips_on          boolean not null default true,
  buy_on           boolean not null default false,
  payout_on        boolean not null default false,
  payout_min_coins integer not null default 100 check (payout_min_coins >= 1),
  max_tip          integer not null default 500 check (max_tip >= 1),
  daily_tip_cap    integer not null default 500 check (daily_tip_cap >= 1),
  platform_fees    bigint  not null default 0,
  updated_at       timestamptz not null default now()
);
insert into bulavata.coin_settings default values;

create table bulavata.coin_bundles (
  id          text primary key check (id ~ '^[a-z0-9_-]{2,32}$'),
  coins       integer not null check (coins > 0),
  bonus       integer not null default 0 check (bonus >= 0),
  price_minor integer not null check (price_minor > 0),
  active      boolean not null default true,
  sort        integer not null default 0
);
insert into bulavata.coin_bundles (id, coins, bonus, price_minor, sort) values
  ('bilo',  50,   0,  500, 1),
  ('tanoa', 100, 10, 1000, 2),
  ('lovo',  250, 50, 2500, 3),
  ('vanua', 500, 150, 5000, 4);

-- ---------------------------------------------------------------- accounts, ledger, tips
create table bulavata.coin_accounts (
  owner      uuid primary key references bulavata.profiles(id) on delete cascade,
  balance    integer not null default 0 check (balance >= 0),   -- coins to give
  earned     integer not null default 0 check (earned >= 0),    -- coins received, waiting to go to the wallet
  bought     integer not null default 0,
  tipped     integer not null default 0,
  received   integer not null default 0,
  paid_out   integer not null default 0,
  updated_at timestamptz not null default now()
);

create table bulavata.coin_ledger (
  id           bigint generated by default as identity primary key,
  owner        uuid references bulavata.profiles(id) on delete cascade,   -- null: Sota Kece's fee
  kind         text not null check (kind in ('buy','tip_out','tip_in','fee','payout','adjust')),
  delta        integer not null check (delta <> 0),
  group_id     uuid not null,
  counterparty uuid references bulavata.profiles(id) on delete set null,
  post_id      bigint references bulavata.talanoa_posts(id) on delete set null,
  reference    text unique,
  memo         text check (memo is null or char_length(memo) <= 80),
  created_at   timestamptz not null default now()
);
create index coin_ledger_owner_idx on bulavata.coin_ledger (owner, created_at desc);
create index coin_ledger_group_idx on bulavata.coin_ledger (group_id);

create table bulavata.coin_tips (
  id         bigint generated by default as identity primary key,
  post_id    bigint not null references bulavata.talanoa_posts(id) on delete cascade,
  giver      uuid not null references bulavata.profiles(id) on delete cascade,
  author     uuid not null references bulavata.profiles(id) on delete cascade,
  coins      integer not null check (coins > 0),
  net        integer not null check (net >= 0),
  note       text check (note is null or char_length(note) <= 60),
  created_at timestamptz not null default now(),
  check (giver <> author)
);
create index coin_tips_post_idx  on bulavata.coin_tips (post_id, created_at desc);
create index coin_tips_giver_idx on bulavata.coin_tips (giver, created_at desc);

